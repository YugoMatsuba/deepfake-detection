"""
Video metadata analysis and integrity verification.

Implements industry-standard forensic techniques for:
- EXIF/metadata extraction and validation (ExifTool)
- Container structural integrity checks (FFmpeg)
- Per-frame hash generation for tamper detection (FFmpeg framemd5)
- Anomaly detection based on established forensic methods

References:
- CVPR 2021: "Forensic Analysis of Video Files Using Metadata" (Xiang & Horváth)
- Fotoforensics metadata tutorial
- Eclipse Forensics timestamp analysis guidelines
- Belkasoft photo forensics (2024)
"""
import subprocess
import json
import os
import re
import logging
from datetime import datetime
from typing import Optional

logger = logging.getLogger(__name__)


def extract_metadata(video_path: str) -> Optional[dict]:
    """
    Extract comprehensive metadata using ExifTool.

    Returns:
        dict with EXIF data (codec, resolution, timestamps, GPS, device info, etc.)
        None if extraction fails
    """
    try:
        cmd = ["exiftool", "-j", video_path]
        result = subprocess.run(
            cmd,
            capture_output=True,
            text=True,
            check=True,
            timeout=30
        )
        data = json.loads(result.stdout)[0]
        return data
    except subprocess.TimeoutExpired:
        logger.error(f"ExifTool timeout for {video_path}")
        return None
    except subprocess.CalledProcessError as e:
        logger.error(f"ExifTool error for {video_path}: {e}")
        return None
    except (json.JSONDecodeError, IndexError) as e:
        logger.error(f"Failed to parse ExifTool output: {e}")
        return None


def check_integrity_ffmpeg(video_path: str) -> str:
    """
    Use FFmpeg to check structural integrity of video container.

    Returns:
        Raw stderr output from FFmpeg (empty if no errors)
    """
    cmd = ["ffmpeg", "-v", "error", "-i", video_path, "-f", "null", "-"]
    result = subprocess.run(
        cmd,
        stdout=subprocess.PIPE,
        stderr=subprocess.PIPE,
        text=True,
        timeout=60
    )
    return result.stderr.strip()


def parse_ffmpeg_log(stderr_text: str) -> dict:
    """
    Convert raw FFmpeg error log into structured integrity report.

    Detects:
    - Macroblock decoding errors (corrupted video blocks)
    - Invalid frame references (broken I/P/B dependencies)
    - Other container/codec errors

    Returns:
        dict with integrity_status ("PASSED" or "FAILED"), errors list, summary
    """
    errors = []

    # Match decoding errors for macroblocks
    mb_errors = re.findall(r'error while decoding MB (\d+) (\d+)', stderr_text)
    for mb in mb_errors:
        errors.append(f"Macroblock at row {mb[0]}, column {mb[1]} failed to decode")

    # Top block unavailable
    if "top block unavailable" in stderr_text:
        errors.append("Top block unavailable for requested intra mode")

    # Reference errors
    references = re.findall(r'Reference (\d+) >= (\d+)', stderr_text)
    for ref in references:
        errors.append(f"Invalid reference: Reference {ref[0]} >= {ref[1]}")

    status = "PASSED" if not errors else "FAILED"

    return {
        "integrity_status": status,
        "errors": errors,
        "summary": f"Video integrity check {status}"
    }


def generate_frame_hashes(video_path: str) -> Optional[list]:
    """
    Generate per-frame MD5 hashes using FFmpeg framemd5 format.

    Returns:
        list of raw framemd5 output lines (to be parsed by parse_frame_hashes)
        None if generation fails
    """
    # DEBUG: Log what we're trying to hash
    print(f"[DEBUG-HASH] ===== ENTERED generate_frame_hashes() =====")
    print(f"[DEBUG-HASH] Attempting to generate frame hashes for: {video_path}")
    print(f"[DEBUG-HASH] File exists: {os.path.exists(video_path)}")
    if os.path.exists(video_path):
        print(f"[DEBUG-HASH] File size: {os.path.getsize(video_path)} bytes")

    cmd = ["ffmpeg", "-i", video_path, "-f", "framemd5", "-"]
    print(f"[DEBUG-HASH] Running command: {' '.join(cmd)}")

    result = subprocess.run(
        cmd,
        stdout=subprocess.PIPE,
        stderr=subprocess.PIPE,
        text=True,
        timeout=120
    )

    print(f"[DEBUG-HASH] FFmpeg return code: {result.returncode}")
    print(f"[DEBUG-HASH] stdout length: {len(result.stdout)} chars")
    print(f"[DEBUG-HASH] stderr length: {len(result.stderr)} chars")

    if result.returncode != 0:
        print(f"[DEBUG-HASH] Error generating frame hashes: {result.stderr[:500]}")
        return None

    hashes = result.stdout.strip().splitlines()
    print(f"[DEBUG-HASH] Parsed {len(hashes)} hash lines from output")
    return hashes


def parse_frame_hashes(raw_hashes: list) -> list:
    """
    Extract MD5 values from FFmpeg framemd5 output.

    FFmpeg framemd5 format:
        # MD5 checksums generated by ffmpeg
        0, 0, 230400, e3b0c44298fc1c149afbf4c8996fb92427ae41e4649b934ca495991b7852b855
        0, 1, 230400, 5d41402abc4b2a76b9719d911017c592

    Returns:
        list of hex hash strings (32+ chars for MD5)
    """
    print(f"[DEBUG-HASH] ===== ENTERED parse_frame_hashes() =====")
    print(f"[DEBUG-HASH] parse_frame_hashes received {len(raw_hashes)} raw lines")
    if raw_hashes and len(raw_hashes) > 0:
        print(f"[DEBUG-HASH] First 3 lines: {raw_hashes[:3]}")

    hashes = []

    for line in raw_hashes:
        if line.startswith('#'):
            continue
        # FFmpeg framemd5 format: stream_index, frame_number, frame_size, hash
        # Parse by splitting on commas and extract 4th field (the hash)
        parts = line.strip().split(',')
        if len(parts) >= 4:
            hash_val = parts[3].strip()
            if hash_val and len(hash_val) >= 32:
                hashes.append(hash_val)

    print(f"[DEBUG-HASH] parse_frame_hashes extracted {len(hashes)} hashes")
    return hashes


def detect_duplicate_frames(frame_hashes_raw: list) -> list:
    """
    Detect duplicate frames using hash comparison.

    Identical hashes indicate:
    - Frame repetition (common in video editing)
    - Potential splicing/insertion

    Returns:
        list of dicts with hash, frame_indices, count
    """
    if not frame_hashes_raw:
        return []

    hashes = parse_frame_hashes(frame_hashes_raw)

    # Build hash frequency map
    hash_map = {}
    for idx, h in enumerate(hashes):
        hash_map.setdefault(h, []).append(idx)

    # Return only duplicates
    duplicates = []
    for h, indices in hash_map.items():
        if len(indices) > 1:
            duplicates.append({
                "hash": h,
                "frame_indices": indices,
                "count": len(indices)
            })

    return duplicates


def detect_image_metadata_anomalies(metadata: dict) -> dict:
    """
    Detect metadata inconsistencies in images using established forensic techniques.

    Based on industry-standard forensic analysis methods adapted for images:
    - Missing critical fields (indicates stripping/tampering) [Fotoforensics]
    - Timestamp logical inconsistencies [Eclipse Forensics]
    - Software field anomalies (editing software detected) [Belkasoft 2024]
    - GPS/timezone mismatches [Amped Authenticate]

    Returns:
        dict with categorized anomalies: {
            "missing_fields": [...],
            "timestamp_issues": [...],
            "software_anomalies": [...],
            "gps_inconsistencies": [...]
        }
    """
    anomalies = {
        "missing_fields": [],
        "timestamp_issues": [],
        "software_anomalies": [],
        "gps_inconsistencies": []
    }

    if not metadata:
        return anomalies

    # 1. MISSING METADATA CHECK (Fotoforensics standard)
    # Critical fields that should be present in authentic camera/phone images
    expected_fields = {
        'FileType', 'MIMEType', 'CreateDate',
        'ImageWidth', 'ImageHeight'
    }
    device_fields = {'Make', 'Model'}

    missing_critical = [f for f in expected_fields if not metadata.get(f)]
    missing_device = [f for f in device_fields if not metadata.get(f)]

    if missing_critical:
        anomalies["missing_fields"].append({
            "type": "critical",
            "fields": missing_critical,
            "note": "Missing basic image metadata"
        })

    if len(missing_device) == len(device_fields):
        anomalies["missing_fields"].append({
            "type": "device_info",
            "fields": list(device_fields),
            "note": "No device information - metadata may be stripped"
        })

    # 2. TIMESTAMP CONSISTENCY (Eclipse Forensics standard)
    create_date = metadata.get('CreateDate') or metadata.get('DateTimeOriginal')
    modify_date = metadata.get('ModifyDate')

    if create_date and modify_date:
        if create_date > modify_date:
            anomalies["timestamp_issues"].append({
                "type": "create_after_modify",
                "create": create_date,
                "modify": modify_date,
                "note": "Create date is after modify date (logically impossible)"
            })

    # 3. SOFTWARE ANOMALIES (Belkasoft 2024 standard)
    # Flag common image editing software
    software = metadata.get('Software', '').lower()
    editing_software = ['photoshop', 'gimp', 'affinity', 'pixelmator', 'paint.net', 'canva']

    if any(edit_sw in software for edit_sw in editing_software):
        anomalies["software_anomalies"].append({
            "type": "editing_software",
            "software": metadata.get('Software'),
            "note": "Editing software detected in metadata - image may be processed/modified"
        })

    # 4. GPS CONSISTENCY
    gps_lat = metadata.get('GPSLatitude')
    gps_long = metadata.get('GPSLongitude')

    if (gps_lat and not gps_long) or (gps_long and not gps_lat):
        anomalies["gps_inconsistencies"].append({
            "type": "incomplete_gps",
            "note": "GPS coordinates incomplete (only latitude or longitude present)"
        })

    return anomalies


def detect_metadata_anomalies(metadata: dict) -> dict:
    """
    Detect metadata inconsistencies in videos using established forensic techniques.

    Based on industry-standard forensic analysis methods:
    - Missing critical fields (indicates stripping/tampering) [Fotoforensics]
    - Timestamp logical inconsistencies [Eclipse Forensics]
    - Software field anomalies (editing software detected) [Belkasoft 2024]
    - GPS/timezone mismatches [Amped Authenticate]

    Returns:
        dict with categorized anomalies: {
            "missing_fields": [...],
            "timestamp_issues": [...],
            "software_anomalies": [...],
            "gps_inconsistencies": [...]
        }
    """
    anomalies = {
        "missing_fields": [],
        "timestamp_issues": [],
        "software_anomalies": [],
        "gps_inconsistencies": []
    }

    if not metadata:
        return anomalies

    # 1. MISSING METADATA CHECK (Fotoforensics standard)
    # Critical fields that should be present in authentic camera/phone videos
    expected_fields = {
        'FileType', 'MIMEType', 'CreateDate',
        'VideoCodec', 'ImageWidth', 'ImageHeight'
    }
    device_fields = {'Make', 'Model', 'Software'}

    missing_critical = [f for f in expected_fields if not metadata.get(f)]
    missing_device = [f for f in device_fields if not metadata.get(f)]

    if missing_critical:
        anomalies["missing_fields"].append({
            "type": "critical",
            "fields": missing_critical,
            "note": "Missing basic video metadata"
        })

    if len(missing_device) == len(device_fields):
        anomalies["missing_fields"].append({
            "type": "device_info",
            "fields": list(device_fields),
            "note": "No device information - metadata may be stripped"
        })

    # 2. TIMESTAMP CONSISTENCY (Eclipse Forensics standard)
    # CreateDate should be <= ModifyDate (basic logic check)
    create_date = metadata.get('CreateDate')
    modify_date = metadata.get('ModifyDate')

    if create_date and modify_date:
        # Simple string comparison (ISO format timestamps sort correctly)
        if create_date > modify_date:
            anomalies["timestamp_issues"].append({
                "type": "create_after_modify",
                "create": create_date,
                "modify": modify_date,
                "note": "Create date is after modify date (logically impossible)"
            })

    # 3. SOFTWARE FIELD ANOMALY (Belkasoft 2024)
    # Editing software in device metadata suggests post-processing
    software = metadata.get('Software', '')
    editing_software = [
        'photoshop', 'premiere', 'final cut', 'davinci',
        'aftereffects', 'ffmpeg', 'handbrake', 'avidemux'
    ]

    if any(editor in software.lower() for editor in editing_software):
        anomalies["software_anomalies"].append({
            "software": software,
            "note": "Editing software detected in metadata - video may be processed/modified"
        })

    # 4. GPS VALIDATION (Amped Authenticate method)
    # If GPS coordinates present, check for basic plausibility
    gps_lat = metadata.get('GPSLatitude')
    gps_lon = metadata.get('GPSLongitude')

    if gps_lat or gps_lon:
        # Basic validation: coordinates should be in valid ranges
        try:
            # Parse latitude (may be in format "37.7749 N" or "37.7749")
            lat_str = str(gps_lat).split()[0] if gps_lat else "0"
            lat_val = float(lat_str)

            if lat_val < -90 or lat_val > 90:
                anomalies["gps_inconsistencies"].append({
                    "field": "GPSLatitude",
                    "value": gps_lat,
                    "note": "GPS latitude out of valid range (-90 to 90)"
                })
        except (ValueError, IndexError):
            pass  # Skip if GPS format is unparseable

        try:
            lon_str = str(gps_lon).split()[0] if gps_lon else "0"
            lon_val = float(lon_str)

            if lon_val < -180 or lon_val > 180:
                anomalies["gps_inconsistencies"].append({
                    "field": "GPSLongitude",
                    "value": gps_lon,
                    "note": "GPS longitude out of valid range (-180 to 180)"
                })
        except (ValueError, IndexError):
            pass

    return anomalies


def run_image_exif_analysis(image_path: str, image_sha256: str) -> dict:
    """
    Analyze image EXIF metadata using ExifTool.

    Reuses existing extract_metadata() and detect_metadata_anomalies() functions.
    Images don't need integrity checks or frame hashes (video-only features).

    Args:
        image_path: Absolute path to image file
        image_sha256: Pre-computed SHA-256 hash from upload (for chain-of-custody)

    Returns:
        dict containing:
        - file_hash: SHA-256 for integrity verification
        - metadata: Raw EXIF data + forensic anomalies
        - analyzed_at: ISO timestamp
    """
    if not os.path.exists(image_path):
        logger.error(f"File not found: {image_path}")
        return {"error": f"File not found: {image_path}"}

    logger.info(f"Running EXIF analysis on image: {image_path}")

    # Extract metadata using ExifTool (works for images too!)
    metadata = extract_metadata(image_path)

    # Detect anomalies using IMAGE-SPECIFIC function
    anomalies = detect_image_metadata_anomalies(metadata) if metadata else {
        "missing_fields": [],
        "timestamp_issues": [],
        "software_anomalies": [],
        "gps_inconsistencies": []
    }

    # Build simplified report (no integrity checks or frame hashes for images)
    return {
        "analyzed_at": datetime.now().isoformat(),
        "file_hash": image_sha256,
        "metadata": {
            "raw": metadata,
            "anomalies": anomalies
        }
    }


def run_metadata_analysis(video_path: str, video_sha256: str) -> dict:
    """
    Analyze video metadata using industry-standard forensic techniques.

    Implements validation methods from:
    - CVPR 2021: "Forensic Analysis of Video Files Using Metadata" (Xiang & Horváth)
    - Fotoforensics metadata tutorial
    - Eclipse Forensics timestamp analysis guidelines
    - Belkasoft photo forensics (2024)

    Args:
        video_path: Absolute path to video file
        video_sha256: Pre-computed SHA-256 hash from upload (for chain-of-custody)

    Returns:
        dict containing:
        - file_hash: SHA-256 for integrity verification
        - metadata: Raw EXIF/container data + forensic anomalies
        - integrity: FFmpeg structural validation
        - frame_hashes: Per-frame MD5 hashes + duplicate detection
    """
    print(f"[DEBUG-HASH] ===== ENTERED run_metadata_analysis() =====")
    print(f"[DEBUG-HASH] video_path param: {video_path}")
    print(f"[DEBUG-HASH] video_sha256 param: {video_sha256}")

    file_exists = os.path.exists(video_path)
    print(f"[DEBUG-HASH] os.path.exists({video_path}): {file_exists}")

    if not file_exists:
        print(f"[DEBUG-HASH] FILE NOT FOUND - returning error")
        logger.error(f"File not found: {video_path}")
        return {"error": f"File not found: {video_path}"}

    print(f"[DEBUG-HASH] File exists, continuing with metadata analysis")
    logger.info(f"Running metadata analysis on: {video_path}")

    # 1. Extract metadata
    print(f"[DEBUG-HASH] Step 1: About to call extract_metadata()")
    metadata = extract_metadata(video_path)
    print(f"[DEBUG-HASH] Step 1 complete: extract_metadata returned {type(metadata)}")

    # 2. Check structural integrity
    print(f"[DEBUG-HASH] Step 2: About to call check_integrity_ffmpeg()")
    ffmpeg_raw = check_integrity_ffmpeg(video_path)
    print(f"[DEBUG-HASH] Step 2a: check_integrity_ffmpeg returned, about to parse")
    integrity_result = parse_ffmpeg_log(ffmpeg_raw)
    print(f"[DEBUG-HASH] Step 2 complete: parse_ffmpeg_log returned")

    # 3. Generate frame hashes
    print(f"[DEBUG-HASH] Step 3: About to call generate_frame_hashes()")
    frame_hashes_raw = generate_frame_hashes(video_path)
    print(f"[DEBUG-HASH] generate_frame_hashes returned: {type(frame_hashes_raw)}, length={len(frame_hashes_raw) if frame_hashes_raw else 0}")
    frame_hashes = parse_frame_hashes(frame_hashes_raw) if frame_hashes_raw else []
    print(f"[DEBUG-HASH] Final frame_hashes count: {len(frame_hashes)}")

    # 4. Detect anomalies and duplicates
    anomalies = detect_metadata_anomalies(metadata) if metadata else {
        "missing_fields": [],
        "timestamp_issues": [],
        "software_anomalies": [],
        "gps_inconsistencies": []
    }
    duplicates = detect_duplicate_frames(frame_hashes_raw) if frame_hashes_raw else []

    # 5. Build report (no file I/O, just return dict)
    print(f"[DEBUG-HASH] Step 5: Building final report, frame_hashes count={len(frame_hashes)}")
    result = {
        "analyzed_at": datetime.now().isoformat(),
        "file_hash": video_sha256,
        "metadata": {
            "raw": metadata,
            "anomalies": anomalies
        },
        "integrity": integrity_result,
        "frame_hashes": {
            "hashes": frame_hashes,
            "count": len(frame_hashes),
            "duplicates": duplicates
        }
    }
    print(f"[DEBUG-HASH] RETURNING from run_metadata_analysis, frame count={len(frame_hashes)}")
    return result
